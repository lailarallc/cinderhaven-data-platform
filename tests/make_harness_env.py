"""Generate the off-host test instance's credentials into tests/harness.env.

The harness's Postgres is a SEPARATE LOCAL TEST SET (U18, owner, 2026-10-20,
spec:DECISIONS#u18-rulings): test rebuilds never carry production's password.
This script generates fresh values and writes them to tests/harness.env, which
is gitignored. tests/harness.env.example is the committed template.

It never reads, copies or prints the platform .env, and it prints no value.

    python tests/make_harness_env.py           # refuses to overwrite
    python tests/make_harness_env.py --force   # regenerate (then recreate the volume)
"""
from __future__ import annotations

import secrets
import sys
from pathlib import Path

HERE = Path(__file__).parent
TARGET = HERE / "harness.env"


def main(argv: list[str]) -> int:
    if TARGET.exists() and "--force" not in argv:
        print(f"{TARGET.name} exists; pass --force to regenerate it.")
        return 0
    TARGET.write_text(
        "# Generated by tests/make_harness_env.py. Local test set only; gitignored.\n"
        "HARNESS_PG_HOST=127.0.0.1\n"
        "HARNESS_PG_PORT=55432\n"
        "HARNESS_PG_DB=cinderhaven\n"
        f"HARNESS_PG_USER=harness_{secrets.token_hex(4)}\n"
        f"HARNESS_PG_PASSWORD={secrets.token_urlsafe(24)}\n",
        encoding="utf-8",
    )
    print(f"Wrote {TARGET} (values not shown).")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
